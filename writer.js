class Writer {
    constructor() {
        this.formatter = {
            format: (output) => output
        };
    }

    async generateOutput(researchData, taskType, plan) {
        console.log('✍️ Generating output...');
        console.log('AI Content available:', !!researchData.aiContent);
        
        if (researchData.aiContent && researchData.aiContent.length > 100) {
            console.log('✅ Using real AI content for output');
            return this.formatAIOutput(researchData);
        }
        
        console.log('❌ No AI content available');
        return this.createErrorOutput(researchData);
    }

    formatAIOutput(researchData) {
        let content = researchData.aiContent;
        
        // Clean up the content - remove duplicate headers if present
        content = this.cleanContent(content);
        
        // Add enhanced footer
        const timestamp = new Date().toLocaleString('en-US', {
            year: 'numeric',
            month: 'long',
            day: 'numeric',
            hour: '2-digit',
            minute: '2-digit'
        });
        
        content += `\n\n<div style="margin-top: 3em; padding-top: 1em; border-top: 2px solid #e0e0e0; color: #666; font-size: 0.9em;">
            <strong>Generated by NuVora AI</strong> • ${timestamp}
        </div>`;
        
        const output = {
            raw: researchData,
            formatted: content,
            html: this.markdownToHTML(content),
            markdown: content,
            timestamp: new Date()
        };
        
        return output;
    }

    cleanContent(content) {
        // Remove duplicate equal sign headers
        content = content.replace(/={3,}/g, '');
        
        // Fix multiple newlines
        content = content.replace(/\n{3,}/g, '\n\n');
        
        // Ensure proper spacing after headers
        content = content.replace(/# (.*?)\n+/g, '# $1\n\n');
        
        return content;
    }

    createErrorOutput(researchData) {
        const errorContent = `# 🚨 Error: Unable to Generate Response

## What happened?
The AI system could not generate a response for your query: **"${researchData.task}"**

## Possible reasons:
1. **Internet connection issues** - Check your network connection
2. **API service temporarily unavailable** - Groq API might be experiencing issues
3. **API key configuration problem** - Verify your API key in .env file
4. **Rate limit exceeded** - You might have reached API call limits

## What to do:
1. **Check your internet connection**
2. **Verify the API key** in your .env file
3. **Visit** [Groq Status](https://status.groq.com) for service updates
4. **Wait a few minutes** and try again
5. **Check server console** for detailed error messages

<div style="margin-top: 2em; padding: 1em; background-color: #f8f9fa; border-left: 4px solid #dc3545; border-radius: 4px;">
    <strong>Technical Details:</strong><br>
    Error occurred at: ${new Date().toLocaleString()}<br>
    Task Type: ${researchData.type || 'Unknown'}<br>
    Query: "${researchData.task}"
</div>`;

        return {
            raw: researchData,
            formatted: errorContent,
            html: this.markdownToHTML(errorContent),
            markdown: errorContent,
            timestamp: new Date()
        };
    }

    markdownToHTML(markdown) {
        if (!markdown) return '';
        
        let html = markdown
            .replace(/^# (.*)$/gm, '<h1 style="border-bottom: 2px solid #4a6cf7; padding-bottom: 10px; margin-bottom: 20px;">$1</h1>')
            .replace(/^## (.*)$/gm, '<h2 style="border-left: 4px solid #4a6cf7; padding-left: 15px; margin: 25px 0 15px 0;">$1</h2>')
            .replace(/^### (.*)$/gm, '<h3 style="color: #2c3e50; margin: 20px 0 10px 0;">$1</h3>')
            .replace(/\*\*(.*?)\*\*/g, '<strong style="font-weight: 700;">$1</strong>')
            .replace(/\*(.*?)\*/g, '<em>$1</em>')
            .replace(/`(.*?)`/g, '<code style="background: #f4f4f4; padding: 2px 6px; border-radius: 4px; font-family: monospace;">$1</code>')
            .replace(/```([\s\S]*?)```/g, '<pre style="background: #2d3748; color: #e2e8f0; padding: 20px; border-radius: 8px; overflow-x: auto; margin: 20px 0;"><code>$1</code></pre>')
            .replace(/\n\n/g, '</p><p style="line-height: 1.6; margin-bottom: 15px;">')
            .replace(/\n/g, '<br>');
        
        // Handle lists
        html = html.replace(/^- (.*)$/gm, '<li style="margin-bottom: 8px;">$1</li>');
        html = html.replace(/(<li[\s\S]*?<\/li>)/g, '<ul style="padding-left: 20px; margin: 15px 0;">$1</ul>');
        
        // Handle numbered lists
        html = html.replace(/^\d+\. (.*)$/gm, '<li style="margin-bottom: 8px;">$1</li>');
        html = html.replace(/(<li[\s\S]*?<\/li>)(?!.*<li)/g, '<ol style="padding-left: 20px; margin: 15px 0;">$1</ol>');
        
        // Wrap in paragraph tags
        if (!html.startsWith('<')) {
            html = '<p style="line-height: 1.6; margin-bottom: 15px;">' + html + '</p>';
        }
        
        // Add container
        html = `<div class="nuvora-output" style="font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Oxygen, Ubuntu, sans-serif; line-height: 1.7; color: #2d3748;">${html}</div>`;
        
        return html;
    }
}

module.exports = Writer;